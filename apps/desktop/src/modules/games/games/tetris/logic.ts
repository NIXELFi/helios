// Pure Tetris engine. No timers, no DOM — the cabinet feeds it actions and
// gravity ticks; every function returns a new state.
//
// Scoring is line clears only (100/300/500/800 × level), deliberately with no
// soft/hard-drop points: every score is a multiple of 100, which is the
// invariant games.scores' plausibility check enforces for 'tetris'.

export const COLS = 10;
export const ROWS = 20;

export type Kind = "I" | "O" | "T" | "S" | "Z" | "J" | "L";
export const KINDS: readonly Kind[] = ["I", "O", "T", "S", "Z", "J", "L"];

/** Cell value: 0 = empty, otherwise 1 + KINDS index (so the colour survives locking). */
export type Board = number[][];

export interface Piece {
  kind: Kind;
  rot: number; // 0..3
  x: number; // column of the shape's 4×4 box
  y: number; // row of the shape's 4×4 box (may be negative while spawning)
}

export interface TetrisState {
  board: Board;
  piece: Piece;
  /** Upcoming kinds; the head is "next". Refilled from a shuffled 7-bag. */
  queue: Kind[];
  hold: Kind | null;
  /** One hold per piece, reset when a piece locks. */
  canHold: boolean;
  score: number;
  lines: number;
  level: number;
  gameOver: boolean;
}

// Shapes as (x, y) cells in a 4×4 box, spawn orientation. Rotations are
// generated by rotating about the box centre, which reproduces SRS states for
// I (4×4) and the 3×3 pieces (offset into the box's top-left 3×3).
const SPAWN: Record<Kind, [number, number][]> = {
  I: [[0, 1], [1, 1], [2, 1], [3, 1]],
  O: [[1, 0], [2, 0], [1, 1], [2, 1]],
  T: [[1, 0], [0, 1], [1, 1], [2, 1]],
  S: [[1, 0], [2, 0], [0, 1], [1, 1]],
  Z: [[0, 0], [1, 0], [1, 1], [2, 1]],
  J: [[0, 0], [0, 1], [1, 1], [2, 1]],
  L: [[2, 0], [0, 1], [1, 1], [2, 1]],
};

function rotateCells(kind: Kind, rot: number): [number, number][] {
  if (kind === "O") return SPAWN.O;
  const size = kind === "I" ? 4 : 3;
  let cells = SPAWN[kind];
  for (let r = 0; r < ((rot % 4) + 4) % 4; r++) {
    cells = cells.map(([x, y]) => [size - 1 - y, x] as [number, number]);
  }
  return cells;
}

/** Board cells (absolute col, row) occupied by `p`. */
export function cellsOf(p: Piece): [number, number][] {
  return rotateCells(p.kind, p.rot).map(([x, y]) => [p.x + x, p.y + y]);
}

export function collides(board: Board, p: Piece): boolean {
  for (const [x, y] of cellsOf(p)) {
    if (x < 0 || x >= COLS || y >= ROWS) return true;
    if (y >= 0 && board[y]![x] !== 0) return true;
  }
  return false;
}

export function emptyBoard(): Board {
  return Array.from({ length: ROWS }, () => Array<number>(COLS).fill(0));
}

/** A shuffled bag of all seven kinds (Fisher–Yates with the injected rng). */
export function bag(rng: () => number): Kind[] {
  const b = [...KINDS];
  for (let i = b.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [b[i], b[j]] = [b[j]!, b[i]!];
  }
  return b;
}

function spawnPiece(kind: Kind): Piece {
  // x = 3 centres every shape on a 10-wide board; the I's cells sit on box row 1.
  return { kind, rot: 0, x: 3, y: kind === "I" ? -1 : 0 };
}

/** Pull the next kind off the queue, keeping at least 7 queued. */
function nextFromQueue(queue: Kind[], rng: () => number): { kind: Kind; queue: Kind[] } {
  let q = queue;
  while (q.length < 8) q = [...q, ...bag(rng)];
  return { kind: q[0]!, queue: q.slice(1) };
}

export function createInitialState(rng: () => number): TetrisState {
  const { kind, queue } = nextFromQueue([], rng);
  return {
    board: emptyBoard(),
    piece: spawnPiece(kind),
    queue,
    hold: null,
    canHold: true,
    score: 0,
    lines: 0,
    level: 1,
    gameOver: false,
  };
}

/** Seconds per gravity row at `level`; floors at 50 ms. */
export function gravityInterval(level: number): number {
  return Math.max(0.05, 0.8 * Math.pow(0.85, level - 1));
}

export const LINE_POINTS = [0, 100, 300, 500, 800] as const;

function tryMove(s: TetrisState, dx: number, dy: number): TetrisState | null {
  const p = { ...s.piece, x: s.piece.x + dx, y: s.piece.y + dy };
  return collides(s.board, p) ? null : { ...s, piece: p };
}

// Simple kick table: in place, then sideways, then up one (floor kick).
const KICKS: [number, number][] = [[0, 0], [-1, 0], [1, 0], [-2, 0], [2, 0], [0, -1]];

function rotate(s: TetrisState, dir: 1 | -1): TetrisState {
  if (s.piece.kind === "O") return s;
  const rot = (s.piece.rot + dir + 4) % 4;
  for (const [dx, dy] of KICKS) {
    const p = { ...s.piece, rot, x: s.piece.x + dx, y: s.piece.y + dy };
    if (!collides(s.board, p)) return { ...s, piece: p };
  }
  return s;
}

/** Write the piece into the board, clear lines, score, and spawn the next one. */
function lock(s: TetrisState, rng: () => number): TetrisState {
  const board = s.board.map((r) => [...r]);
  const v = KINDS.indexOf(s.piece.kind) + 1;
  let toppedOut = false;
  for (const [x, y] of cellsOf(s.piece)) {
    if (y < 0) toppedOut = true;
    else board[y]![x] = v;
  }
  const kept = board.filter((r) => r.some((c) => c === 0));
  const cleared = ROWS - kept.length;
  const fresh = Array.from({ length: cleared }, () => Array<number>(COLS).fill(0));
  const nextBoard = [...fresh, ...kept];
  const lines = s.lines + cleared;
  const score = s.score + LINE_POINTS[cleared]! * s.level;
  const level = 1 + Math.floor(lines / 10);
  const { kind, queue } = nextFromQueue(s.queue, rng);
  const piece = spawnPiece(kind);
  const gameOver = toppedOut || collides(nextBoard, piece);
  return { ...s, board: nextBoard, piece, queue, canHold: true, score, lines, level, gameOver };
}

/** Row the piece would land on if hard-dropped (for the ghost). */
export function dropY(s: TetrisState): number {
  let p = s.piece;
  while (!collides(s.board, { ...p, y: p.y + 1 })) p = { ...p, y: p.y + 1 };
  return p.y;
}

export type Action = "left" | "right" | "down" | "rotateCw" | "rotateCcw" | "drop" | "hold" | "tick";

/** Apply one input (or a gravity `tick`). "down" and "tick" lock a grounded piece. */
export function step(s: TetrisState, action: Action, rng: () => number): TetrisState {
  if (s.gameOver) return s;
  switch (action) {
    case "left": return tryMove(s, -1, 0) ?? s;
    case "right": return tryMove(s, 1, 0) ?? s;
    case "rotateCw": return rotate(s, 1);
    case "rotateCcw": return rotate(s, -1);
    case "down":
    case "tick": return tryMove(s, 0, 1) ?? lock(s, rng);
    case "drop": return lock({ ...s, piece: { ...s.piece, y: dropY(s) } }, rng);
    case "hold": {
      if (!s.canHold) return s;
      if (s.hold === null) {
        const { kind, queue } = nextFromQueue(s.queue, rng);
        return { ...s, hold: s.piece.kind, piece: spawnPiece(kind), queue, canHold: false };
      }
      const piece = spawnPiece(s.hold);
      return { ...s, hold: s.piece.kind, piece, canHold: false, gameOver: collides(s.board, piece) };
    }
  }
}
