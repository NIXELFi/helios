-- 5. RPCs ------------------------------------------------------------------------------

-- Any team member asks to be paid back. Execs are told who asked and for what.
create or replace function finance.request_reimbursement(
  p_amount_cents bigint, p_reason text, p_date date default null,
  p_project uuid default null, p_subteam uuid default null, p_item uuid default null)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_uid uuid := auth.uid(); v_name text; v_id bigint;
begin
  if v_uid is null then raise exception 'authentication required' using errcode = '42501'; end if;
  if not purchasing.is_member() then raise exception 'only team members can ask to be reimbursed' using errcode = '42501'; end if;
  if p_amount_cents is null or p_amount_cents <= 0 then raise exception 'enter the amount you paid' using errcode = '22023'; end if;
  if coalesce(btrim(p_reason), '') = '' then raise exception 'say what it was for' using errcode = '22023'; end if;
  v_name := purchasing.display_name(v_uid);
  insert into finance.reimbursements (person_name, user_id, amount_cents, reason, project_id, subteam_id,
                                      item_id, requested_date, status)
  values (v_name, v_uid, p_amount_cents, left(btrim(p_reason), 500), p_project, p_subteam, p_item,
          coalesce(p_date, purchasing.team_day()), 'requested')
  returning id into v_id;
  perform purchasing.notify(
    array(select u from unnest(purchasing.users_with('finance.edit')) u where u <> v_uid), null, 'reimbursement',
    v_name || ' asked to be reimbursed $' || to_char(p_amount_cents / 100.0, 'FM999999990.00') || ' for '
    || left(btrim(p_reason), 120) || '. Check the receipts in Finance > Reimbursements.');
  return v_id;
end; $$;

-- The requester withdraws a request that hasn't been decided yet. (The app
-- deletes the receipt files first; the owner may while it is 'requested'.)
create or replace function finance.withdraw_reimbursement(p_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
begin
  delete from finance.reimbursements
  where id = p_id and user_id = auth.uid() and status = 'requested';
  if not found then
    raise exception 'only your own request, before an exec has looked at it' using errcode = '42501';
  end if;
end; $$;

-- An exec accepts a request (it becomes money owed) or turns it down.
create or replace function finance.decide_reimbursement(p_id bigint, p_decision text, p_note text default '')
returns void language plpgsql security definer set search_path = '' as $$
declare v finance.reimbursements;
begin
  if not finance.can_edit() then raise exception 'only execs decide reimbursements' using errcode = '42501'; end if;
  if p_decision not in ('approve', 'deny') then raise exception 'decision must be approve or deny' using errcode = '22023'; end if;
  select * into v from finance.reimbursements where id = p_id for update;
  if not found then raise exception 'no such reimbursement' using errcode = 'P0002'; end if;
  if v.status <> 'requested' then raise exception 'that reimbursement was already decided' using errcode = '22023'; end if;
  if v.user_id = auth.uid() then
    raise exception 'another exec has to decide your own reimbursement' using errcode = '42501';
  end if;
  update finance.reimbursements set
    status = case when p_decision = 'approve' then 'owed' else 'denied' end,
    denied_reason = case when p_decision = 'deny' then coalesce(p_note, '') else '' end,
    decided_by = auth.uid(), decided_at = now()
  where id = p_id;
  perform purchasing.notify(array[v.user_id], null, 'reimbursement',
    case when p_decision = 'approve'
      then 'Your reimbursement for ' || left(v.reason, 80) || ' ($' || to_char(coalesce(v.amount_cents, 0) / 100.0, 'FM999999990.00')
           || ') was approved. You''ll be paid by check.'
      else 'Your reimbursement for ' || left(v.reason, 80) || ' was declined' || coalesce(': ' || nullif(p_note, ''), '.') end);
end; $$;

-- Mark reimbursements paid, optionally writing one check for them into the
-- ledger (as an uncashed check on the checking account). One check pays one
-- person.
create or replace function finance.pay_reimbursements(
  p_ids bigint[], p_paid_date date default null, p_check_number text default null, p_add_check boolean default false)
returns bigint language plpgsql security definer set search_path = '' as $$
declare
  v_people int; v_person text; v_total bigint; v_txn bigint; v_checking bigint; v_reasons text;
  v_date date := coalesce(p_paid_date, purchasing.team_day()); v_check text := nullif(btrim(coalesce(p_check_number, '')), '');
begin
  if not finance.can_edit() then raise exception 'only execs pay reimbursements' using errcode = '42501'; end if;
  if coalesce(array_length(p_ids, 1), 0) = 0 then raise exception 'pick at least one' using errcode = '22023'; end if;
  -- lock the rows so two execs paying at once can't both write a check
  perform 1 from finance.reimbursements where id = any (p_ids) for update;
  if (select count(*) from finance.reimbursements where id = any (p_ids)) <> (select count(distinct x) from unnest(p_ids) x) then
    raise exception 'some of those reimbursements don''t exist' using errcode = 'P0002';
  end if;
  if exists (select 1 from finance.reimbursements where id = any (p_ids) and user_id = auth.uid()) then
    raise exception 'another exec has to pay your own reimbursement' using errcode = '42501';
  end if;
  if exists (select 1 from finance.reimbursements where id = any (p_ids) and status in ('requested', 'denied')) then
    raise exception 'approve the requests before paying them' using errcode = '22023';
  end if;
  if exists (select 1 from finance.reimbursements where id = any (p_ids) and status = 'paid') then
    raise exception 'some of those were already paid' using errcode = '22023';
  end if;
  if p_add_check then
    select count(distinct lower(btrim(person_name))), min(person_name), sum(coalesce(amount_cents, 0)),
           string_agg(reason, '; ')
      into v_people, v_person, v_total, v_reasons
      from finance.reimbursements where id = any (p_ids);
    if v_people <> 1 then raise exception 'one check pays one person: pick one person''s rows' using errcode = '22023'; end if;
    if v_check is null then raise exception 'enter the check number' using errcode = '22023'; end if;
    if v_total <= 0 then raise exception 'the amounts are missing' using errcode = '22023'; end if;
    select id into v_checking from finance.accounts where kind = 'checking' and active order by id limit 1;
    if v_checking is null then raise exception 'no checking account' using errcode = 'P0002'; end if;
    if exists (select 1 from finance.transactions where account_id = v_checking and kind = 'check' and reference = v_check) then
      raise exception 'check #% is already in the ledger', v_check using errcode = '23505';
    end if;
    insert into finance.transactions (account_id, date, amount_cents, description, kind, category, reference, source, notes)
    values (v_checking, v_date, -v_total, 'Reimbursement check to ' || v_person || ': ' || left(v_reasons, 300),
            'check', 'Reimbursement', v_check, 'manual', 'Written for ' || array_length(p_ids, 1) || ' reimbursement(s)')
    returning id into v_txn;
  end if;
  update finance.reimbursements set
    status = 'paid', paid_date = coalesce(paid_date, v_date),
    check_number = coalesce(v_check, check_number), check_txn_id = coalesce(v_txn, check_txn_id)
  where id = any (p_ids);
  perform purchasing.notify(
    array(select distinct user_id from finance.reimbursements where id = any (p_ids)), null, 'reimbursement',
    'Your reimbursement was paid' || coalesce(' by check #' || v_check, '') || '.');
  return v_txn;
end; $$;

-- Replace a transaction's split. Shares must add up to the transaction's amount.
-- p_allocations: [{project_id, subteam_id, amount_cents}]
create or replace function finance.set_allocations(p_txn bigint, p_allocations jsonb, p_basis text default 'manual')
returns void language plpgsql security definer set search_path = '' as $$
declare v_amount bigint; v_kind text; v_sum bigint;
begin
  if not finance.can_edit() then raise exception 'only execs edit the ledger' using errcode = '42501'; end if;
  select abs(amount_cents), kind into v_amount, v_kind from finance.transactions where id = p_txn for update;
  if not found then raise exception 'no such transaction' using errcode = 'P0002'; end if;
  if exists (select 1 from jsonb_array_elements(coalesce(p_allocations, '[]')) a where (a ->> 'amount_cents')::bigint < 0) then
    raise exception 'each share is a positive amount' using errcode = '22023';
  end if;
  select coalesce(sum((a ->> 'amount_cents')::bigint), 0) into v_sum from jsonb_array_elements(coalesce(p_allocations, '[]')) a;
  if jsonb_array_length(coalesce(p_allocations, '[]')) > 0 and v_kind <> 'transfer' and v_sum <> v_amount then
    raise exception 'the split must add up to $%; it adds up to $%',
      to_char(v_amount / 100.0, 'FM999999990.00'), to_char(v_sum / 100.0, 'FM999999990.00') using errcode = '22023';
  end if;
  delete from finance.txn_allocations where txn_id = p_txn;
  insert into finance.txn_allocations (txn_id, project_id, subteam_id, amount_cents)
  select p_txn, nullif(a ->> 'project_id', '')::uuid, (a ->> 'subteam_id')::uuid, (a ->> 'amount_cents')::bigint
  from jsonb_array_elements(coalesce(p_allocations, '[]')) a;
  update finance.transactions set allocation_basis = case when jsonb_array_length(coalesce(p_allocations, '[]')) > 0
    then coalesce(p_basis, 'manual') else '' end where id = p_txn;
end; $$;

-- A charge's subteam split, built from the parts linked to it (weighted by
-- each part's cost and its car/subteam percentages). Used while the split
-- is still one Helios made from parts; a split an exec entered is left alone.
create or replace function finance.split_from_parts(p_txn bigint)
returns void language plpgsql security definer set search_path = '' as $$
declare v_amount bigint; v_kind text; v_basis text;
begin
  select abs(amount_cents), kind, allocation_basis into v_amount, v_kind, v_basis from finance.transactions where id = p_txn;
  if not found or v_kind = 'transfer' then return; end if;
  if exists (select 1 from finance.txn_allocations where txn_id = p_txn) and v_basis not like 'from part%' then return; end if;
  delete from finance.txn_allocations where txn_id = p_txn;
  with w as (
    select a.project_id, a.subteam_id, sum(greatest(purchasing.item_cost(i), 1) * a.percent) as weight
    from purchasing.items i join purchasing.item_allocations a on a.item_id = i.id
    where i.finance_txn_id = p_txn
    group by a.project_id, a.subteam_id
  ), r as (
    select project_id, subteam_id, round(v_amount * weight / sum(weight) over ())::bigint as share,
           row_number() over (order by subteam_id, project_id) as n, count(*) over () as cnt
    from w
  )
  insert into finance.txn_allocations (txn_id, project_id, subteam_id, amount_cents)
  select p_txn, project_id, subteam_id,
         case when n = cnt   -- the last share takes the rounding, so the split adds up exactly
              then v_amount - coalesce(sum(share) over (order by n rows between unbounded preceding and 1 preceding), 0)
              else share end
  from r;
  update finance.transactions set allocation_basis = coalesce(
    'from parts ' || (select string_agg(code, ', ' order by code) from purchasing.items where finance_txn_id = p_txn), '')
  where id = p_txn;
end; $$;

-- Link a parts-list item to the statement line that paid for it (null to
-- unlink). A received item that is linked becomes RECONCILED. The charge it
-- leaves and the charge it joins have their parts-based splits rebuilt, so
-- the money counts once, toward the right subteams.
create or replace function finance.link_item(p_item uuid, p_txn bigint)
returns void language plpgsql security definer set search_path = '' as $$
declare v_old bigint;
begin
  if not finance.can_edit() then raise exception 'only execs edit the ledger' using errcode = '42501'; end if;
  select finance_txn_id into v_old from purchasing.items where id = p_item for update;
  if not found then raise exception 'no such item' using errcode = 'P0002'; end if;
  update purchasing.items set
    finance_txn_id = p_txn,
    match_method = case when p_txn is null then 'rejected' else 'manual' end,
    status = case when p_txn is not null and status = 'RECEIVED' then 'RECONCILED'
                  when p_txn is null and status = 'RECONCILED' then 'RECEIVED' else status end,
    reconciled_at = case when p_txn is not null and status = 'RECEIVED' then now() else reconciled_at end
  where id = p_item;
  if v_old is not null and v_old is distinct from p_txn then perform finance.split_from_parts(v_old); end if;
  if p_txn is not null then perform finance.split_from_parts(p_txn); end if;
end; $$;

-- 6. Budgets from the ledger ---------------------------------------------------------------
--
-- Spent     = charges in the ledger, by their split, plus ordered items paid
--             outside the ledger (ASU money, a member's own card)
-- Committed = approved or ordered items whose charge isn't in the ledger yet
-- Planned   = items still "not ready" or "ready to order"
-- Once an item is linked to its statement line it counts through the ledger,
-- never twice. Members only get the lines for their own subteams.

-- Every share of money that counts toward a budget, with what it came from.
-- Internal: only budget_rows() and budget_detail() call it, and they filter
-- by the caller's scope.
create or replace function purchasing.budget_shares(p_season uuid default null)
returns table (
  project_id uuid, subteam_id uuid, bucket text, cents bigint,
  source text, ref text, on_date date, label text, txn_id bigint, item_id uuid)
language sql stable security definer set search_path = '' as $$
  with season as (
    select s.id, s.starts_on, s.ends_on from purchasing.seasons s
    where s.id = coalesce(p_season, (select id from purchasing.seasons where is_current))
  )
  -- parts-list items that aren't in the ledger yet
  select a.project_id, a.subteam_id,
         case
           when i.status in ('PLANNED', 'READY') then 'planned'
           when i.status in ('ORDERED', 'BACKORDERED', 'SHIPPED', 'DELIVERED', 'RECEIVED', 'RECONCILED')
                and (i.paid_by <> '' or i.payment_method ~* '(asu|dean|personal|reimburs|foundation)') then 'spent'
           else 'committed'
         end,
         round(purchasing.item_cost(i) * a.percent / 100.0)::bigint,
         'part', i.code, coalesce(i.ordered_at, purchasing.team_day(i.created_at)), i.title, null::bigint, i.id
  from purchasing.items i
  join purchasing.item_allocations a on a.item_id = i.id
  where i.status not in ('DENIED', 'CANCELLED', 'HAVE')
    and i.finance_txn_id is null
    and (i.season_id is null or i.season_id = (select id from season))
  union all
  -- ledger spending: charges count positive, refunds and card credits negative, transfers never
  select al.project_id, al.subteam_id, 'spent',
         case when t.amount_cents > 0 then -al.amount_cents else al.amount_cents end,
         'ledger', coalesce(t.reference, ''), t.date,
         -- a check's memo can name the person paid back; show only "Check"
         -- (and a withdrawal's, e.g. a Zelle payee): members see only the kind
         coalesce(nullif(t.vendor, ''), case when t.kind in ('check', 'withdrawal') then initcap(t.kind) else t.description end), t.id, null::uuid
  from finance.transactions t
  join finance.txn_allocations al on al.txn_id = t.id
  where t.status = 'posted' and t.kind in ('charge', 'check', 'withdrawal', 'fee', 'credit')
    and ((select starts_on from season) is null or t.date >= (select starts_on from season))
    and ((select ends_on from season) is null or t.date <= (select ends_on from season));
$$;

drop function if exists purchasing.budget_rows(uuid);
create or replace function purchasing.budget_rows(p_season uuid default null)
returns table (
  budget_line_id uuid, project_id uuid, project_code text, name text, subteam_ids uuid[],
  budget_cents bigint, spent_cents bigint, committed_cents bigint, planned_cents bigint)
language sql stable security definer set search_path = '' as $$
  with season as (
    select coalesce(p_season, (select id from purchasing.seasons where is_current)) as id
  ),
  lines as (
    select l.id, l.project_id, l.name, l.amount_cents,
           array_agg(ls.subteam_id) filter (where ls.subteam_id is not null) as subteams
    from purchasing.budget_lines l
    left join purchasing.budget_line_subteams ls on ls.budget_line_id = l.id
    where l.season_id = (select id from season)
    group by l.id
  ),
  line_of as (
    select s.*, (select l.id from lines l
                 where l.project_id is not distinct from s.project_id and s.subteam_id = any (l.subteams) limit 1) as line_id
    from purchasing.budget_shares(p_season) s
  )
  select l.id, l.project_id, p.car_code, l.name, coalesce(l.subteams, '{}'),
         l.amount_cents,
         coalesce(sum(x.cents) filter (where x.bucket = 'spent'), 0)::bigint,
         coalesce(sum(x.cents) filter (where x.bucket = 'committed'), 0)::bigint,
         coalesce(sum(x.cents) filter (where x.bucket = 'planned'), 0)::bigint
  from lines l
  join pm.projects p on p.id = l.project_id
  left join line_of x on x.line_id = l.id
  where purchasing.is_exec()
     or exists (select 1 from unnest(l.subteams) st where pm.has_capability((select auth.uid()), 'purchasing.view', st))
  group by l.id, l.project_id, p.car_code, l.name, l.subteams, l.amount_cents
  union all
  -- spending on a subteam no budget line covers is shown, never dropped
  select null, x.project_id, coalesce(p.car_code, 'Team'), '(no budget line) ' || st.name, array[x.subteam_id], 0,
         coalesce(sum(x.cents) filter (where x.bucket = 'spent'), 0)::bigint,
         coalesce(sum(x.cents) filter (where x.bucket = 'committed'), 0)::bigint,
         coalesce(sum(x.cents) filter (where x.bucket = 'planned'), 0)::bigint
  from line_of x
  left join pm.projects p on p.id = x.project_id
  join pm.subteams st on st.id = x.subteam_id
  where x.line_id is null
    and (purchasing.is_exec() or pm.has_capability((select auth.uid()), 'purchasing.view', x.subteam_id))
  group by x.project_id, p.car_code, st.name, x.subteam_id;
$$;

-- What makes up one budget row: every part and ledger share for that car and
-- those subteams. Members only get their own subteams' shares, and see a
-- charge's vendor, date and amount but never a link into the ledger.
create or replace function purchasing.budget_detail(p_project uuid, p_subteams uuid[], p_season uuid default null)
returns table (bucket text, source text, ref text, on_date date, label text, cents bigint, txn_id bigint, item_id uuid)
language sql stable security definer set search_path = '' as $$
  select s.bucket, s.source, s.ref, s.on_date, s.label, s.cents,
         case when finance.can_view() then s.txn_id end, s.item_id
  from purchasing.budget_shares(p_season) s
  where s.project_id is not distinct from p_project
    and s.subteam_id = any (p_subteams)
    and (purchasing.is_exec() or pm.has_capability((select auth.uid()), 'purchasing.view', s.subteam_id))
  order by case s.bucket when 'spent' then 0 when 'committed' then 1 else 2 end, s.on_date desc nulls last;
$$;

-- 7. Import support ---------------------------------------------------------------------
--
-- The import from the old ledger keeps its ids (so discrepancy keys and the
-- resolutions made there still line up). Afterwards, move every id counter
-- past the imported rows. Service role only.
create or replace function finance.sync_ids()
returns void language plpgsql security definer set search_path = '' as $$
declare t text; v_max bigint;
begin
  foreach t in array array['accounts', 'statements', 'transactions', 'txn_allocations', 'evidence',
                            'balance_entries', 'reimbursements', 'reimbursement_receipts'] loop
    execute format('select max(id) from finance.%I', t) into v_max;
    perform setval(pg_get_serial_sequence('finance.' || t, 'id'), greatest(coalesce(v_max, 0), 1), v_max is not null);
  end loop;
  select max(nullif(regexp_replace(code, '\D', '', 'g'), '')::bigint) into v_max from purchasing.items;
  perform setval('purchasing.item_code_seq', greatest(coalesce(v_max, 0), 1), v_max is not null);
end; $$;

