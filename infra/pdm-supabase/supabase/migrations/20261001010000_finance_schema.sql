-- Write one uploaded file. Execs only.
--   p_file:       {sha256, file_name, format, account_id}
--   p_statement:  optional {account_id, period_start, closing_date, opening_cents,
--                 ending_cents, net_charges_cents, purchases_cents, credits_cents}
--   p_rows:       new transactions (same fields as finance.transactions; lines
--                 whose source_key already exists are skipped)
--   p_clears:     [{txn_id, cleared_date}] checks already in the ledger that cleared
--   p_confirms:   [{transfer_group, date, amount_cents?}] expected transfers (card autopay) that happened
--   p_balances:   [{account_id, as_of, balance_cents, note, source_key}] bank-reported balances
create or replace function finance.import_transactions(
  p_file jsonb, p_statement jsonb default null, p_rows jsonb default '[]', p_clears jsonb default '[]',
  p_confirms jsonb default '[]', p_balances jsonb default '[]')
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_stmt bigint; v_added int := 0; v_n int; v_cleared int := 0; v_confirmed int := 0; v_bal int := 0; r jsonb;
begin
  if not finance.can_edit() then raise exception 'only execs can upload statements' using errcode = '42501'; end if;
  if coalesce(p_file ->> 'sha256', '') = '' then raise exception 'missing file fingerprint' using errcode = '22023'; end if;
  if exists (select 1 from finance.imports where sha256 = p_file ->> 'sha256') then
    raise exception 'that file was already imported' using errcode = '23505';
  end if;

  if p_statement is not null then
    insert into finance.statements (account_id, period_start, closing_date, opening_cents, ending_cents,
                                    net_charges_cents, purchases_cents, credits_cents, source_file, sha256)
    values ((p_statement ->> 'account_id')::bigint, nullif(p_statement ->> 'period_start', '')::date,
            (p_statement ->> 'closing_date')::date, nullif(p_statement ->> 'opening_cents', '')::bigint,
            nullif(p_statement ->> 'ending_cents', '')::bigint, coalesce((p_statement ->> 'net_charges_cents')::bigint, 0),
            coalesce((p_statement ->> 'purchases_cents')::bigint, 0), coalesce((p_statement ->> 'credits_cents')::bigint, 0),
            p_file ->> 'file_name', p_file ->> 'sha256')
    returning id into v_stmt;
  end if;

  for r in select * from jsonb_array_elements(coalesce(p_rows, '[]')) loop
    insert into finance.transactions (account_id, date, post_date, cleared_date, amount_cents, description, vendor,
      kind, category, reference, status, transfer_group, needs_review, review_note, source, source_key, statement_id, notes)
    values ((r ->> 'account_id')::bigint, (r ->> 'date')::date, nullif(r ->> 'post_date', '')::date,
            nullif(r ->> 'cleared_date', '')::date, (r ->> 'amount_cents')::bigint, coalesce(r ->> 'description', ''),
            nullif(r ->> 'vendor', ''), r ->> 'kind', coalesce(nullif(r ->> 'category', ''), 'Needs category'),
            nullif(r ->> 'reference', ''), coalesce(nullif(r ->> 'status', ''), 'posted'), nullif(r ->> 'transfer_group', ''),
            coalesce((r ->> 'needs_review')::boolean, false), coalesce(r ->> 'review_note', ''),
            coalesce(nullif(r ->> 'source', ''), p_file ->> 'format'), r ->> 'source_key',
            case when (r ->> 'account_id')::bigint = (p_statement ->> 'account_id')::bigint then v_stmt end,
            coalesce(r ->> 'notes', ''))
    on conflict (source_key) do nothing;
    get diagnostics v_n = row_count;
    v_added := v_added + v_n;
  end loop;

  for r in select * from jsonb_array_elements(coalesce(p_clears, '[]')) loop
    update finance.transactions set cleared_date = (r ->> 'cleared_date')::date
    where id = (r ->> 'txn_id')::bigint and kind = 'check' and cleared_date is null;
    get diagnostics v_n = row_count;
    v_cleared := v_cleared + v_n;
  end loop;

  for r in select * from jsonb_array_elements(coalesce(p_confirms, '[]')) loop
    -- amount_cents (optional, positive): what was actually paid, when it
    -- differs from what was expected; each side keeps its sign
    update finance.transactions set status = 'posted', date = (r ->> 'date')::date, post_date = (r ->> 'date')::date,
      cleared_date = (r ->> 'date')::date, notes = trim(notes || ' Confirmed by ' || (p_file ->> 'file_name') || '.'),
      amount_cents = case when nullif(r ->> 'amount_cents', '') is null then amount_cents
                          else sign(amount_cents) * abs((r ->> 'amount_cents')::bigint) end
    where transfer_group = r ->> 'transfer_group' and status = 'expected';
    get diagnostics v_n = row_count;
    v_confirmed := v_confirmed + v_n;
  end loop;

  for r in select * from jsonb_array_elements(coalesce(p_balances, '[]')) loop
    insert into finance.balance_entries (account_id, as_of, balance_cents, measure, confirmed, note, entered_by_name, source_key)
    values ((r ->> 'account_id')::bigint, (r ->> 'as_of')::date, (r ->> 'balance_cents')::bigint, 'balance', true,
            coalesce(r ->> 'note', ''), 'Bank export', r ->> 'source_key')
    on conflict (source_key) do nothing;
    get diagnostics v_n = row_count;
    v_bal := v_bal + v_n;
  end loop;

  insert into finance.imports (sha256, file_name, format, account_id, rows_added)
  values (p_file ->> 'sha256', p_file ->> 'file_name', p_file ->> 'format', nullif(p_file ->> 'account_id', '')::bigint, v_added);

  return jsonb_build_object('added', v_added, 'cleared', v_cleared, 'confirmed', v_confirmed, 'balances', v_bal,
                            'statement_id', v_stmt);
end; $$;

