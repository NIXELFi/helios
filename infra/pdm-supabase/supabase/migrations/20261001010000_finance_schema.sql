-- Finance (Phase B of docs/superpowers/specs/2026-09-28-purchasing-and-finance-design.md)
--
-- The exec ledger: every account (Chase checking, the SAE card, Square, ASU
-- accounts, GoFundMe), every statement line, weekly balances, reimbursements,
-- and the evidence (invoices, order emails) that explains each charge.
--
-- Who sees what:
--   * Execs (finance.view / finance.edit, org-wide) see and edit everything.
--   * Any team member may REQUEST a reimbursement and attach receipts, and
--     sees only their own requests. Nothing else here is visible to them.
--   * Budgets stay per-subteam: purchasing.budget_rows() (redefined below to
--     count spending from the ledger) only returns lines in the caller's scope.
--
-- The counting rule: money counts once, on the statement line where it moved.
-- A card purchase counts on the card; the monthly payment from checking is a
-- transfer. Invoices, order emails and parts-list rows never add money; they
-- are evidence linked to a statement line.
--
-- Amounts are integer cents. Signs on every account: negative = money leaving
-- the team, positive = money arriving. Only the last four digits of a card or
-- account number are ever stored.
--
-- Ids are bigint (not uuid) so that discrepancy keys ("no-invoice:13") are
-- stable and match the ledger this replaces.

create schema if not exists finance;
grant usage on schema finance to authenticated, service_role;

create or replace function finance.can_view()
returns boolean language sql stable security definer set search_path = '' as $$
  select pm.has_capability((select auth.uid()), 'finance.view', null);
$$;
create or replace function finance.can_edit()
returns boolean language sql stable security definer set search_path = '' as $$
  select pm.has_capability((select auth.uid()), 'finance.edit', null);
$$;

