-- 2. Audit trigger ---------------------------------------------------------------

create or replace function finance.audit()
returns trigger language plpgsql security definer set search_path = '' as $$
declare k text; o jsonb; n jsonb; v_id text;
begin
  if tg_op = 'DELETE' then
    o := to_jsonb(old);
    v_id := coalesce(o ->> 'id', o ->> 'key', o ->> 'name', '');
    insert into finance.events (actor_id, entity, entity_id, field, old_value)
    values ((select auth.uid()), tg_table_name, v_id, '*deleted*', left(o::text, 2000));
    return old;
  end if;
  n := to_jsonb(new);
  v_id := coalesce(n ->> 'id', n ->> 'key', n ->> 'name', '');
  if tg_op = 'INSERT' then
    insert into finance.events (actor_id, entity, entity_id, field, new_value)
    values ((select auth.uid()), tg_table_name, v_id, '*created*', left(n::text, 2000));
    return new;
  end if;
  o := to_jsonb(old);
  for k in select jsonb_object_keys(n) loop
    if k <> 'updated_at' and (o -> k) is distinct from (n -> k) then
      insert into finance.events (actor_id, entity, entity_id, field, old_value, new_value)
      values ((select auth.uid()), tg_table_name, v_id, k, o ->> k, n ->> k);
    end if;
  end loop;
  if n ? 'updated_at' then new.updated_at := now(); end if;
  return new;
end; $$;

do $$
declare t text;
begin
  foreach t in array array['accounts', 'categories', 'transactions', 'txn_allocations', 'evidence',
                            'balance_entries', 'reimbursements', 'reimbursement_receipts',
                            'discrepancy_resolutions'] loop
    execute format('create trigger %1$s_audit_ins after insert on finance.%1$s for each row execute function finance.audit()', t);
    execute format('create trigger %1$s_audit_upd before update on finance.%1$s for each row execute function finance.audit()', t);
    execute format('create trigger %1$s_audit_del after delete on finance.%1$s for each row execute function finance.audit()', t);
  end loop;
end $$;

